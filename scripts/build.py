#!/usr/bin/env python3
"""Build derived artefacts from the CRRA CSV tables.

  database/*.csv  ->  website/data/data.js          (embedded, so the site needs no server)
                  ->  database/master_database.xlsx (one sheet per table + a Summary sheet)

The CSVs are the single source of truth. Nothing here invents, infers or reformats
record content; it only reshapes what the CSVs already hold.
"""
import csv, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB = os.path.join(ROOT, "database")
WEB_DATA = os.path.join(ROOT, "website", "data")

TABLES = [
    ("rna_records.csv", "RNA Records", "rnas"),
    ("interactions.csv", "Interactions", "interactions"),
    ("cancer_associations.csv", "Cancer Associations", "associations"),
    ("publications.csv", "Publications", "publications"),
]

FONT = "Arial"


def read(name):
    path = os.path.join(DB, name)
    if not os.path.exists(path):
        print(f"  ! {name} not found - skipping")
        return [], []
    with open(path, newline="", encoding="utf-8") as fh:
        reader = csv.DictReader(fh)
        rows = list(reader)
        return reader.fieldnames or [], rows


def build_js(data):
    os.makedirs(WEB_DATA, exist_ok=True)
    out = os.path.join(WEB_DATA, "data.js")
    payload = json.dumps(data, indent=1, ensure_ascii=False)
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("// Generated by scripts/build.py from database/*.csv - do not edit by hand.\n")
        fh.write("window.CRRA_DATA = ")
        fh.write(payload)
        fh.write(";\n")
    # A JSON copy too, for anyone who wants the data without the site.
    with open(os.path.join(WEB_DATA, "data.json"), "w", encoding="utf-8") as fh:
        fh.write(payload + "\n")
    print(f"  wrote {out}")


def build_xlsx(tables):
    try:
        from openpyxl import Workbook
        from openpyxl.styles import Font, PatternFill, Alignment
        from openpyxl.utils import get_column_letter
    except ImportError:
        print("  ! openpyxl unavailable - skipping workbook")
        return None

    NAVY = "1F3864"
    wb = Workbook()
    wb.remove(wb.active)

    header_font = Font(name=FONT, bold=True, color="FFFFFF", size=11)
    header_fill = PatternFill("solid", fgColor=NAVY)
    body_font = Font(name=FONT, size=10)

    sheet_rows = {}
    for sheet_name, fields, rows in tables:
        ws = wb.create_sheet(sheet_name)
        sheet_rows[sheet_name] = len(rows)
        if not fields:
            ws["A1"] = "No data: source CSV missing or empty"
            ws["A1"].font = body_font
            continue

        # Readable headers: snake_case -> Title Case.
        ws.append([f.replace("_", " ").title() for f in fields])
        for cell in ws[1]:
            cell.font = header_font
            cell.fill = header_fill
            cell.alignment = Alignment(vertical="center", wrap_text=True)
        ws.row_dimensions[1].height = 28

        for r in rows:
            ws.append([r.get(f, "") for f in fields])
        for row in ws.iter_rows(min_row=2):
            for cell in row:
                cell.font = body_font
                cell.alignment = Alignment(vertical="top", wrap_text=True)

        ws.freeze_panes = "A2"
        ws.auto_filter.ref = f"A1:{get_column_letter(len(fields))}{max(ws.max_row, 2)}"

        # Width from content, capped so long prose does not blow the layout out.
        for i, f in enumerate(fields, start=1):
            longest = max([len(f)] + [len(str(r.get(f, ""))) for r in rows] or [len(f)])
            ws.column_dimensions[get_column_letter(i)].width = min(max(12, longest + 2), 55)

    # --- Summary sheet: live formulas, not baked-in numbers -----------------
    ws = wb.create_sheet("Summary", 0)
    ws["A1"] = "Cancer Regulatory RNA Atlas"
    ws["A1"].font = Font(name=FONT, bold=True, size=14, color=NAVY)
    ws["A2"] = "An evidence-based resource for exploring noncoding RNA regulation in human cancer."
    ws["A2"].font = Font(name=FONT, italic=True, size=10)
    ws["A4"] = "Counts below are formulas over the data sheets; they update if a sheet changes."
    ws["A4"].font = Font(name=FONT, size=9, italic=True)

    ws["A6"], ws["B6"] = "Table", "Rows"
    for cell in (ws["A6"], ws["B6"]):
        cell.font = header_font
        cell.fill = header_fill

    row = 7
    for sheet_name, fields, _ in tables:
        ws.cell(row=row, column=1, value=sheet_name).font = body_font
        if fields:
            key = f"'{sheet_name}'!A:A" if " " in sheet_name else f"{sheet_name}!A:A"
            c = ws.cell(row=row, column=2, value=f"=COUNTA({key})-1")
        else:
            c = ws.cell(row=row, column=2, value=0)
        c.font = body_font
        c.number_format = "#,##0"
        row += 1

    # Evidence-class mix, counted across both evidence-bearing tables.
    row += 1
    ws.cell(row=row, column=1, value="Evidence class").font = header_font
    ws.cell(row=row, column=1).fill = header_fill
    ws.cell(row=row, column=2, value="Records").font = header_font
    ws.cell(row=row, column=2).fill = header_fill
    row += 1

    def col_of(sheet_name, field):
        for s, fields, _ in tables:
            if s == sheet_name and field in fields:
                return get_column_letter(fields.index(field) + 1)
        return None

    ic, ac = col_of("Interactions", "evidence_class"), col_of("Cancer Associations", "evidence_class")
    for label in ("Direct experimental", "Experimental functional",
                  "Computational prediction", "Literature association"):
        ws.cell(row=row, column=1, value=label).font = body_font
        parts = []
        if ic:
            parts.append(f'COUNTIF(Interactions!{ic}:{ic},"{label}")')
        if ac:
            parts.append(f"COUNTIF('Cancer Associations'!{ac}:{ac},\"{label}\")")
        c = ws.cell(row=row, column=2, value=("=" + "+".join(parts)) if parts else 0)
        c.font = body_font
        c.number_format = "#,##0"
        row += 1

    row += 1
    ws.cell(row=row, column=1,
            value="See documentation/limitations.md. Counts reflect curation effort, "
                  "not how common anything is in biology.").font = Font(name=FONT, size=9, italic=True)

    ws.column_dimensions["A"].width = 34
    ws.column_dimensions["B"].width = 12
    ws.freeze_panes = "A7"

    out = os.path.join(DB, "master_database.xlsx")
    wb.save(out)
    print(f"  wrote {out}")
    return out


def main():
    print("Reading CSVs...")
    data, tables = {}, []
    for fname, sheet, key in TABLES:
        fields, rows = read(fname)
        data[key] = rows
        tables.append((sheet, fields, rows))
        print(f"  {fname}: {len(rows)} rows")

    data["_meta"] = {
        "generated_from": "database/*.csv",
        "evidence_classes": ["Direct experimental", "Experimental functional",
                             "Computational prediction", "Literature association"],
        "note": "Counts reflect curation effort, not biological frequency. "
                "See documentation/limitations.md",
    }

    print("Building website data...")
    build_js(data)
    print("Building workbook...")
    path = build_xlsx(tables)
    if path:
        print("\nWorkbook contains formulas on the Summary sheet; run:")
        print(f"  python3 scripts/recalc.py {os.path.relpath(path, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
